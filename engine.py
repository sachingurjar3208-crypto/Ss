# ── Player of the Month (POTM) Bonus ─────────────────────────────────────────
# Cards belonging to the POTM event get a +25% boost to their higher stat
# (batting or bowling), +20% to OVR, and +10% to the lower stat.
_POTM_BOOST = 1.25
_POTM_OVR_BOOST = 1.20
_POTM_LOWER_BOOST = 1.10


def is_potm_event(inst) -> bool:
    """Return True if the instance belongs to the Player of the Month (POTM) event special."""
    try:
        special = getattr(inst, "special", None)
        if special is None:
            return False
        name = getattr(special, "name", "") or ""
        is_event = getattr(special, "is_event", False)
        upper = name.strip().upper()
        return is_event and ("POTM" in upper or "PLAYER OF THE MONTH" in upper)
    except Exception:
        return False


def apply_potm_boost(ovr: int, bat: int, bowl: int) -> tuple[int, int, int]:
    """Apply the POTM bonus: 1.25x to the higher stat, 1.10x to the lower stat, 1.20x to OVR."""
    if not (ovr or bat or bowl):
        return ovr, bat, bowl
    if bat >= bowl:
        bat = int(round(bat * _POTM_BOOST))
        bowl = int(round(bowl * _POTM_LOWER_BOOST))
    else:
        bowl = int(round(bowl * _POTM_BOOST))
        bat = int(round(bat * _POTM_LOWER_BOOST))
    ovr = int(round(ovr * _POTM_OVR_BOOST))
    return ovr, bat, bowl


# ── Special Memories Player Detection ───────────────────────────────────────
_MEMORIES_SPECIAL_PLAYERS = {
    "chris gayle": "gayle",
    "brendon mccullum": "mccullum",
}


def get_memories_player_type(inst) -> str | None:
    """Return the special player type if this is a MEMORIES special card, else None."""
    try:
        special = getattr(inst, "special", None)
        if special is None:
            ball = getattr(inst, "ball", None)
            if ball is not None:
                special = getattr(ball, "special", None)
        if special is None:
            return None
        if not getattr(special, "is_event", False):
            return None
        if getattr(special, "name", "").strip().upper() != "MEMORIES":
            return None
        name = getattr(inst, "country", None) or ""
        if not name and hasattr(inst, "ball"):
            name = getattr(inst.ball, "country", "") or ""
        name = name.lower().strip()
        for key, val in _MEMORIES_SPECIAL_PLAYERS.items():
            if key in name:
                return val
    except Exception:
        pass
    return None


# ── Database Instance Helpers ─────────────────────────────────────────────────
def get_cricket_stats(ball) -> tuple[int, int, int]:
    """Fetch OVR, BAT, and BOWL stats from capacity_logic."""
    try:
        logic = getattr(ball, "capacity_logic", None) or {}
        ovr = logic.get("ovr", 0)
        bat = logic.get("bat_power", 0)
        bowl = logic.get("bowl_power", 0)
        return int(ovr), int(bat), int(bowl)
    except Exception:
        return 0, 0, 0


def get_card_role(ball) -> str:
    """Determine primary playing role of the card from capacity_logic."""
    try:
        logic = getattr(ball, "capacity_logic", None) or {}
        role = logic.get("role")
        if role:
            return role
    except Exception:
        pass
    return "Bat"


def compute_ovr_from_rarity(rarity: float) -> int:
    if not rarity:
        return 99
    r = min(max(float(rarity), 0.0), 1.0)
    return max(1, min(99, int(round(99 - 98 * r))))


def is_match_eligible(ball) -> bool:
    """Validate if a card is eligible to be used in live T20 matches."""
    try:
        cap = getattr(ball, "capacity_name", "").lower()
        return cap not in ["team", "duo", "trio", "custom"]
    except Exception:
        return True


# ── Exchange Value ─────────────────────────────────────────────────────────
# Currency value assigned to a card for /sell and /exchange.
# Based on rarity (the badge rarity shown on the card) and special type.


def _rarity_to_base_value(rarity: float) -> int:
    """Convert rarity to base exchange value (before event multipliers)."""
    if not rarity or rarity <= 0:
        return 1

    r = float(rarity)

    exact = {
        0.01: 2000,
        0.02: 1200,
        0.03: 1000,
        0.05: 500,
        0.08: 200,
        0.1: 50,
        0.2: 20,
        0.3: 12,
        0.4: 8,
        0.5: 7,
        0.6: 6,
    }
    if r in exact:
        return exact[r]

    if 0.7 <= r <= 1.0:
        return 5
    if 1.0 < r < 5.0:
        return 3
    if 5.0 <= r < 10.0:
        return 2
    if 10.0 <= r < 20.0:
        return 1
    if r >= 20.0:
        return 1

    return 1


def compute_exchange_value(
    ball,
    special_name: str | None = None,
    is_event: bool = False,
    is_prime_event: bool = False,
) -> int:
    """Compute the currency exchange value for a card.

    Tier 1 (base value from rarity):
        - Non-event cards (no special)
        - ICONS event
        - Prime Event cards (Ball.prime_event=True)

    Tier 2 (2x base):
        - Signature Edition Event
        - Premium Edition Event

    Tier 3 (1.25x base):
        - All other events

    Shiny specials (5x base):
        - Any card with a Shiny special overlay
    """
    logic = getattr(ball, "capacity_logic", None) or {}
    badge_r = logic.get("badge_rarity")
    if badge_r is not None:
        try:
            rarity = float(badge_r)
        except (TypeError, ValueError):
            rarity = float(getattr(ball, "rarity", 1.0) or 1.0)
    else:
        rarity = float(getattr(ball, "rarity", 1.0) or 1.0)

    base = _rarity_to_base_value(rarity)

    if is_prime_event:
        return base
    if is_event and special_name and special_name.strip().upper() == "ICONS":
        return base

    if special_name and special_name.strip().lower() == "shiny":
        return base * 5

    if special_name and special_name.strip().lower() == "transformers":
        return base * 2

    if is_event and special_name:
        upper = special_name.strip().upper()
        if "PREMIUM" in upper or "SIGNATURE" in upper:
            return base * 2

    if is_event:
        return int(round(base * 1.25))

    return base


