def get_narrative_attributes(ball) -> list[str]:
    """Return list of active narrative attribute keys from ball.capacity_logic['narrative']."""
    try:
        logic = getattr(ball, "capacity_logic", None) or {}
        narrative = logic.get("narrative")
        if not narrative:
            return []
        if isinstance(narrative, dict):
            attrs = narrative.get("attributes", [])
            if isinstance(attrs, list):
                return [a for a in attrs if a in NARRATIVE_ATTRIBUTES]
        return []
    except Exception:
        return []


def get_narrative_effect(ball, attribute: str) -> dict:
    """Return the effect dict for a specific narrative attribute."""
    return NARRATIVE_ATTRIBUTES.get(attribute, {})
